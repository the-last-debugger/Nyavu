"""Builds the Android blocklist from public, freely licensed sources.

    python tools/make_blocklist.py

Writes android/app/src/main/assets/blocklist.txt. Every source is free to use;
re-run before a demonstration so the list is current.
"""
from __future__ import annotations

import os
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "app", "src", "main", "assets", "blocklist.txt")

SOURCES = [
    # StevenBlack's consolidated hosts list (MIT-style, widely used)
    "https://raw.githubusercontent.com/StevenBlack/hosts/master/hosts",
]

def main() -> None:
    domains: set[str] = set()
    for url in SOURCES:
        try:
            req = urllib.request.Request(url, headers={"User-Agent": "Nyavu blocklist builder"})
            text = urllib.request.urlopen(req, timeout=60).read().decode("utf-8", "ignore")
        except Exception as exc:                      # keep going if one source is down
            print("skipped", url, exc)
            continue
        for line in text.splitlines():
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            parts = line.split()
            host = parts[1] if len(parts) >= 2 else parts[0]
            host = host.lower().strip(".")
            if host and "." in host and not host.startswith("0.0.0.0"):
                domains.add(host)
        print(f"{url}: {len(domains):,} domains so far")

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("# generated by tools/make_blocklist.py\n")
        fh.write("\n".join(sorted(domains)))
    print(f"wrote {len(domains):,} domains -> {OUT}")

if __name__ == "__main__":
    main()
